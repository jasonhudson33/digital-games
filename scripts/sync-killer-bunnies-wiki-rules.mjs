import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const API = "https://killerbunnies.fandom.com/api.php";
const OUTPUT = resolve("lib/killer-bunnies-card-wiki-rules.generated.js");
const CATEGORIES = [
  "Blue Starter Deck (Quest)", "Yellow Booster Deck (Quest)", "Red Booster Deck (Quest)",
  "Violet Booster Deck (Quest)", "Orange Booster Deck (Quest)", "Green Booster Deck (Quest)",
  "Twilight White Booster Deck (Quest)", "Stainless Steel Booster Deck (Quest)",
  "Perfectly Pink Booster Deck (Quest)", "Wacky Khaki Booster Deck (Quest)",
  "Ominous Onyx Booster Deck (Quest)", "Chocolate Booster Deck (Quest)",
  "Blue Starter Deck (Conquest)", "Yellow Booster Deck (Conquest)", "Red Booster Deck (Conquest)",
  "Violet Booster Deck (Conquest)", "Fantastic Booster Deck (Quest)",
  "Caramel Swirl Booster Deck (Quest)", "Creature Feature Booster Deck (Quest)",
  "Pumpkin Spice Booster Deck (Quest)", "La-Di-Da London Booster Deck (Quest)",
  "Cake Batter Booster Deck (Quest)", "Radioactive Robots Booster Deck (Quest)",
  "Almond Crisp Booster Deck (Quest)",
];

const titles = new Set();
for (const category of CATEGORIES) {
  for (const title of await categoryMembers(category)) titles.add(title);
  process.stdout.write(`Found ${titles.size} card pages through ${category}.\n`);
}

const records = new Map();
const titleList = [...titles].sort();
for (let index = 0; index < titleList.length; index += 40) {
  const pages = await pageSources(titleList.slice(index, index + 40));
  for (const page of pages) addPageRecords(records, page);
  process.stdout.write(`Read ${Math.min(index + 40, titleList.length)} / ${titleList.length} pages.\n`);
}

const lines = [
  "// Generated by scripts/sync-killer-bunnies-wiki-rules.mjs.",
  "// Short excerpts are community cross-checks; official Bunny Bits remain authoritative.",
  "export const KILLER_BUNNIES_WIKI_RULES = Object.freeze({",
];
for (const [cin, record] of [...records].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`  ${JSON.stringify(cin)}: Object.freeze(${JSON.stringify(record)}),`);
}
lines.push("});", "");
await writeFile(OUTPUT, lines.join("\n"));
process.stdout.write(`Wrote ${records.size} CIN rule records to ${OUTPUT}.\n`);

async function categoryMembers(category) {
  const members = [];
  let continuation = "";
  do {
    const params = new URLSearchParams({
      action: "query", format: "json", list: "categorymembers", cmtitle: `Category:${category}`,
      cmlimit: "500", cmnamespace: "0",
    });
    if (continuation) params.set("cmcontinue", continuation);
    const payload = await fetchJson(`${API}?${params}`);
    members.push(...(payload.query?.categorymembers || []).map((entry) => entry.title));
    continuation = payload.continue?.cmcontinue || "";
  } while (continuation);
  return members;
}

async function pageSources(pageTitles) {
  const params = new URLSearchParams({
    action: "query", format: "json", formatversion: "2", prop: "revisions",
    rvprop: "content", rvslots: "main", titles: pageTitles.join("|"),
  });
  const payload = await fetchJson(`${API}?${params}`);
  return (payload.query?.pages || []).filter((page) => !page.missing).map((page) => ({
    title: page.title,
    wikitext: page.revisions?.[0]?.slots?.main?.content || "",
  }));
}

async function fetchJson(url) {
  let lastError;
  for (let attempt = 1; attempt <= 5; attempt += 1) {
    try {
      const response = await fetch(url, { headers: { "user-agent": "DigitalGamesCardAudit/1.0" } });
      if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
      return await response.json();
    } catch (error) {
      lastError = error;
      await new Promise((resolveDelay) => setTimeout(resolveDelay, attempt * 350));
    }
  }
  throw lastError;
}

function addPageRecords(records, page) {
  const cardIds = [...field(page.wikitext, "cardid").matchAll(/\b(\d{4})\b/g)]
    .map((match) => match[1]);
  if (!cardIds.length) return;
  const excerpt = shortRuleExcerpt(page.wikitext);
  if (!excerpt) return;
  const type = field(page.wikitext, "type");
  const aggressive = /^yes$/i.test(field(page.wikitext, "aggressive"));
  const sourceUrl = `https://killerbunnies.fandom.com/wiki/${encodeURIComponent(page.title.replaceAll(" ", "_"))}`;
  for (const cin of new Set(cardIds)) {
    if (cin === "0997" && page.title === "Feed the Bunny") continue;
    records.set(cin, { excerpt, type, aggressive, sourceUrl, sourceTitle: page.title });
  }
}

function field(wikitext, name) {
  return wikitext.match(new RegExp(`^\\|${name}\\s*=\\s*(.+)$`, "im"))?.[1]?.trim() || "";
}

function shortRuleExcerpt(wikitext) {
  const afterInfobox = wikitext.slice(Math.max(0, wikitext.indexOf("}}") + 2));
  const intro = afterInfobox.split(/^==/m)[0]
    .replace(/<ref\b[^>]*>[\s\S]*?<\/ref>|<ref\b[^/>]*\/>/gi, " ")
    .replace(/\[\[[^\]|]+\|([^\]]+)\]\]/g, "$1")
    .replace(/\[\[([^\]]+)\]\]/g, "$1")
    .replace(/\{\{[^{}]*\}\}/g, " ")
    .replace(/'{2,}/g, "")
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  if (intro.length < 12 || /^category:/i.test(intro)) return "";
  const words = intro.split(" ");
  const clipped = words.slice(0, 24).join(" ");
  return words.length > 24 ? `${clipped.replace(/[.,;:]$/, "")}…` : clipped;
}
