export const KILLER_BUNNIES_CATALOG_COUNT = CARD_NAMES.length;
export const KILLER_BUNNIES_DECK_CATALOG = DECKS;

export const KILLER_BUNNIES_CARD_CATALOG = Object.freeze(
  CARD_NAMES.map((name, index) => createCatalogCard(index + 1, name)),
);

const CARDS_BY_NUMBER = new Map(KILLER_BUNNIES_CARD_CATALOG.map((card) => [card.number, card]));

export function getKillerBunniesCatalogCard(number) {
  return CARDS_BY_NUMBER.get(Number(number)) || null;
}

export function getKillerBunniesCatalogCardsForDeck(deckId) {
  return KILLER_BUNNIES_CARD_CATALOG.filter((card) => card.deckId === deckId);
}

export function validateKillerBunniesCardCatalog(cards = KILLER_BUNNIES_CARD_CATALOG) {
  const numbers = cards.map((card) => card.number);
  const ids = cards.map((card) => card.id);
  const duplicateNumbers = numbers.filter((number, index) => numbers.indexOf(number) !== index);
  const duplicateIds = ids.filter((id, index) => ids.indexOf(id) !== index);
  const missingNumbers = [];
  for (let number = 1; number <= cards.length; number += 1) {
    if (!numbers.includes(number)) missingNumbers.push(number);
  }
  return {
    valid: cards.length === 1485 && !duplicateNumbers.length && !duplicateIds.length && !missingNumbers.length,
    count: cards.length,
    duplicateNumbers: [...new Set(duplicateNumbers)],
    duplicateIds: [...new Set(duplicateIds)],
    missingNumbers,
  };
}

function createCatalogCard(number, name) {
  const deck = DECKS.find((entry) => number >= entry.firstNumber && number <= entry.lastNumber);
  const classification = classifyCard(name);
  const catalogNumber = String(number).padStart(4, "0");
  const printedType = getKillerBunniesPrintedCardType(catalogNumber);
  const classifiedCard = { ...classification, type: printedType || classification.type };
  const inferredRules = getKillerBunniesCardRules({ number, catalogNumber, name, deckId: deck.id, deckName: deck.name, ...classifiedCard });
  const { printedType: rulesPrintedType, ...rules } = inferredRules;
  const finalType = printedType || rulesPrintedType || classification.type;
  return Object.freeze({
    id: `kbq-${catalogNumber}`,
    number,
    catalogNumber,
    name,
    deckId: deck.id,
    deckName: deck.name,
    series: deck.series,
    deckColor: deck.color,
    ...classifiedCard,
    type: finalType,
    ...rules,
    printedTypeVerified: Boolean(printedType),
    detail: rules.ability,
    source: "Official Killer Bunnies deck checklist",
  });
}

function classifyCard(name) {
  const normalized = name.toLowerCase();
  const costs = resourceCosts(name);
  const weaponLevel = name.match(/weapon\s+leve(?:l|r)\s*:?\s*(\d+|50\/50)/i)?.[1] || null;
  const color = name.match(/(?:^|[\s/–-])(Blue|Green|Orange|Yellow|Violet|Red|Pink|White|Black|Brown)(?:$|[\s/–-])/i)?.[1]?.toLowerCase() || null;

  if (/^carrot\s+#/i.test(name)) {
    return { kind: "carrot", type: "CARROT", color, carrotNumber: Number(name.match(/#(\d+)/)?.[1] || 0), confidence: "exact" };
  }
  if (/^choose\s+(?:a|\d+)\s+carrots?/i.test(name)) {
    const amount = name.match(/^choose\s+(\d+)/i)?.[1];
    return { kind: "chooseCarrot", type: "RUN", carrotCount: amount ? Number(amount) : 1, confidence: "exact" };
  }
  if (/^(?:feed|gorge)\s+the\s+bunny|^random\s+ftb/i.test(name)) {
    return { kind: "feed", type: "RUN", costs, randomCost: /^random\s+ftb/i.test(name), confidence: "exact" };
  }
  if (weaponLevel || /dated\s+weapon/i.test(name)) {
    return { kind: "weapon", type: "RUN", power: weaponLevel && /^\d+$/.test(weaponLevel) ? Number(weaponLevel) : null, weaponLevel, confidence: "exact" };
  }
  if (/^(?:kaballa\s+dolla|bunny\s+bytes?)\s*[–-]/i.test(name)) {
    return { kind: "money", type: "CURRENCY", value: Number(name.match(/[–-]\s*(\d+)\s*$/)?.[1] || 0), confidence: "exact" };
  }
  if (looksLikeBunny(name)) {
    return { kind: "bunny", type: "RUN", color, confidence: "inferred" };
  }
  if (/bunny\s+modifier/i.test(name)) {
    return { kind: "modifier", type: "RUN", color, cloverValue: getKillerBunniesCloverValue({ name }), confidence: "exact" };
  }
  if (/terrible\s+misfortune/i.test(name)) {
    return { kind: "misfortune", type: "PLAY IMMEDIATELY", confidence: "exact" };
  }
  if (/kaballa|rooney|weil.+pawn shop|store/i.test(normalized)) {
    return { kind: "market", type: "MARKET", confidence: "inferred" };
  }
  return { kind: "action", type: "ACTION", confidence: "unverified" };
}

function looksLikeBunny(name) {
  return /^(?:congenial|gleeful|lumbering|sinister|timid|evil|hypnotic|ludicrous|spiffy|truculent|specialty|celebrity|semi-super specialty|super specialty|extra super|half-color|officer ranked|enlisted ranked|robot|cathexis|law enforcement|holographic|british)\s+bunny\b/i.test(name)
    || /^(?:double\s+)?free agent$/i.test(name)
    || /^enginerds$/i.test(name)
    || /\bbunny\s*[–-]\s*(?:blue|green|orange|yellow|violet|red|pink)(?:\b|\/)/i.test(name);
}

function resourceCosts(name) {
  const costs = {};
  for (const match of name.matchAll(/(\d+)\s+(cabbage|water|radish|milk)/gi)) {
    costs[match[2].toLowerCase()] = Number(match[1]);
  }
  return Object.freeze(costs);
}

function deck(id, name, series, firstNumber, lastNumber, color) {
  return Object.freeze({ id, name, series, firstNumber, lastNumber, color, cardCount: lastNumber - firstNumber + 1 });
}
